BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'AUDIT_LOGS', 'OPERATING_EXPENSES', 'WASTAGE', 'INVENTORY_MOVEMENTS',
        'SALES_ITEMS', 'SALES', 'PURCHASE_ITEMS', 'PURCHASES',
        'PRODUCTS', 'SUPPLIERS', 'CATEGORIES', 'USERS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
    FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_name LIKE 'SEQ_%') LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
    END LOOP;
END;
/

-- 1. USERS
CREATE TABLE USERS (
    USER_ID         NUMBER          PRIMARY KEY,
    USERNAME        VARCHAR2(50)    UNIQUE NOT NULL,
    PASSWORD_HASH   VARCHAR2(255)   NOT NULL,
    FULL_NAME       VARCHAR2(100),
    ROLE            VARCHAR2(20)    DEFAULT 'STAFF' NOT NULL,
    STATUS          VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT CHK_USER_ROLE CHECK (ROLE IN ('ADMIN', 'STAFF')),
    CONSTRAINT CHK_USER_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

-- 2. CATEGORIES
CREATE TABLE CATEGORIES (
    CATEGORY_ID     NUMBER          PRIMARY KEY,
    CATEGORY_NAME   VARCHAR2(100)   UNIQUE NOT NULL,
    DESCRIPTION     VARCHAR2(500),
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL
);

-- 3. SUPPLIERS
CREATE TABLE SUPPLIERS (
    SUPPLIER_ID     NUMBER          PRIMARY KEY,
    SUPPLIER_CODE   VARCHAR2(30)    UNIQUE NOT NULL,
    SUPPLIER_NAME   VARCHAR2(150)   NOT NULL,
    PHONE           VARCHAR2(30),
    CITY            VARCHAR2(100),
    STATUS          VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT CHK_SUPPLIER_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

-- 4. PRODUCTS
CREATE TABLE PRODUCTS (
    PRODUCT_ID              NUMBER          PRIMARY KEY,
    PRODUCT_CODE            VARCHAR2(30)    UNIQUE NOT NULL,
    PRODUCT_NAME            VARCHAR2(150)   NOT NULL,
    CATEGORY_ID             NUMBER          NOT NULL,
    UNIT                    VARCHAR2(20)    DEFAULT 'kg' NOT NULL,
    PURCHASE_COST           NUMBER(10,2)    DEFAULT 0 NOT NULL,
    SELLING_PRICE           NUMBER(10,2)    NOT NULL,
    CURRENT_STOCK           NUMBER(12,3)    DEFAULT 0 NOT NULL,
    REORDER_LEVEL           NUMBER(12,3)    DEFAULT 10 NOT NULL,
    CURRENT_AVERAGE_COST    NUMBER(10,2)    DEFAULT 0 NOT NULL,
    PREFERRED_SUPPLIER_ID   NUMBER,
    STATUS                  VARCHAR2(20)    DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT              DATE            DEFAULT SYSDATE NOT NULL,
    UPDATED_AT              DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_PROD_CAT FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID),
    CONSTRAINT FK_PROD_SUPP FOREIGN KEY (PREFERRED_SUPPLIER_ID) REFERENCES SUPPLIERS(SUPPLIER_ID),
    CONSTRAINT CHK_PROD_UNIT CHECK (UNIT IN ('kg', 'g', 'piece', 'bunch', 'packet', 'litre')),
    CONSTRAINT CHK_PROD_PUR_COST CHECK (PURCHASE_COST >= 0),
    CONSTRAINT CHK_PROD_SELL_PRICE CHECK (SELLING_PRICE >= 0),
    CONSTRAINT CHK_PROD_STOCK CHECK (CURRENT_STOCK >= 0),
    CONSTRAINT CHK_PROD_REORDER CHECK (REORDER_LEVEL >= 0),
    CONSTRAINT CHK_PROD_AVG_COST CHECK (CURRENT_AVERAGE_COST >= 0),
    CONSTRAINT CHK_PROD_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

-- 5. PURCHASES HEADER
CREATE TABLE PURCHASES (
    PURCHASE_ID     NUMBER          PRIMARY KEY,
    PURCHASE_REF    VARCHAR2(50)    UNIQUE NOT NULL,
    SUPPLIER_ID     NUMBER          NOT NULL,
    PURCHASE_DATE   DATE            DEFAULT TRUNC(SYSDATE) NOT NULL,
    TOTAL_AMOUNT    NUMBER(12,2)    DEFAULT 0 NOT NULL,
    STATUS          VARCHAR2(20)    DEFAULT 'COMPLETED' NOT NULL,
    NOTES           VARCHAR2(500),
    CREATED_BY      NUMBER,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_PURCH_SUPP FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIERS(SUPPLIER_ID),
    CONSTRAINT FK_PURCH_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_PURCH_STATUS CHECK (STATUS IN ('COMPLETED', 'REVERSED')),
    CONSTRAINT CHK_PURCH_TOTAL CHECK (TOTAL_AMOUNT >= 0)
);

-- 6. PURCHASE_ITEMS
CREATE TABLE PURCHASE_ITEMS (
    PURCHASE_ITEM_ID    NUMBER          PRIMARY KEY,
    PURCHASE_ID         NUMBER          NOT NULL,
    PRODUCT_ID          NUMBER          NOT NULL,
    QUANTITY            NUMBER(12,3)    NOT NULL,
    UNIT_COST           NUMBER(10,2)    NOT NULL,
    DISCOUNT_AMOUNT     NUMBER(10,2)    DEFAULT 0 NOT NULL,
    LINE_TOTAL          NUMBER(12,2)    NOT NULL,
    CONSTRAINT FK_PI_PURCHASE FOREIGN KEY (PURCHASE_ID) REFERENCES PURCHASES(PURCHASE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_PI_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT CHK_PI_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CHK_PI_COST CHECK (UNIT_COST >= 0),
    CONSTRAINT CHK_PI_DISC CHECK (DISCOUNT_AMOUNT >= 0),
    CONSTRAINT CHK_PI_TOTAL CHECK (LINE_TOTAL >= 0)
);

-- 7. SALES HEADER (End-of-Day or Batch Sales)
CREATE TABLE SALES (
    SALE_ID         NUMBER          PRIMARY KEY,
    SALE_REF        VARCHAR2(50)    UNIQUE NOT NULL,
    SALE_DATE       DATE            DEFAULT TRUNC(SYSDATE) NOT NULL,
    TOTAL_REVENUE   NUMBER(12,2)    DEFAULT 0 NOT NULL,
    TOTAL_COGS      NUMBER(12,2)    DEFAULT 0 NOT NULL,
    TOTAL_PROFIT    NUMBER(12,2)    DEFAULT 0 NOT NULL,
    STATUS          VARCHAR2(20)    DEFAULT 'FINALIZED' NOT NULL,
    NOTES           VARCHAR2(500),
    CREATED_BY      NUMBER,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    UPDATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_SALE_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_SALE_STATUS CHECK (STATUS IN ('DRAFT', 'FINALIZED', 'REVERSED')),
    CONSTRAINT CHK_SALE_REV CHECK (TOTAL_REVENUE >= 0),
    CONSTRAINT CHK_SALE_COGS CHECK (TOTAL_COGS >= 0)
);

-- 8. SALES_ITEMS
CREATE TABLE SALES_ITEMS (
    SALES_ITEM_ID       NUMBER          PRIMARY KEY,
    SALE_ID             NUMBER          NOT NULL,
    PRODUCT_ID          NUMBER          NOT NULL,
    QUANTITY            NUMBER(12,3)    NOT NULL,
    SELLING_PRICE       NUMBER(10,2)    NOT NULL,
    UNIT_COST_AT_SALE   NUMBER(10,2)    DEFAULT 0 NOT NULL,
    DISCOUNT_AMOUNT     NUMBER(10,2)    DEFAULT 0 NOT NULL,
    LINE_TOTAL          NUMBER(12,2)    NOT NULL,
    COST_OF_GOODS_SOLD  NUMBER(12,2)    DEFAULT 0 NOT NULL,
    CONSTRAINT FK_SI_SALE FOREIGN KEY (SALE_ID) REFERENCES SALES(SALE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_SI_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT CHK_SI_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CHK_SI_PRICE CHECK (SELLING_PRICE >= 0),
    CONSTRAINT CHK_SI_COST CHECK (UNIT_COST_AT_SALE >= 0),
    CONSTRAINT CHK_SI_DISC CHECK (DISCOUNT_AMOUNT >= 0),
    CONSTRAINT CHK_SI_TOTAL CHECK (LINE_TOTAL >= 0),
    CONSTRAINT CHK_SI_COGS CHECK (COST_OF_GOODS_SOLD >= 0)
);

-- 9. INVENTORY_MOVEMENTS (Double-entry stock ledger)
CREATE TABLE INVENTORY_MOVEMENTS (
    MOVEMENT_ID         NUMBER          PRIMARY KEY,
    PRODUCT_ID          NUMBER          NOT NULL,
    MOVEMENT_DATE       DATE            DEFAULT SYSDATE NOT NULL,
    MOVEMENT_TYPE       VARCHAR2(30)    NOT NULL,
    QUANTITY_CHANGE     NUMBER(12,3)    NOT NULL,
    UNIT_COST           NUMBER(10,2)    DEFAULT 0 NOT NULL,
    REFERENCE_TYPE      VARCHAR2(30),
    REFERENCE_ID        NUMBER,
    REASON              VARCHAR2(255),
    CREATED_BY          NUMBER,
    CREATED_AT          DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_MOV_PROD FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT FK_MOV_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_MOV_TYPE CHECK (MOVEMENT_TYPE IN ('OPENING_STOCK', 'PURCHASE', 'SALE', 'WASTAGE', 'ADJUSTMENT', 'PURCHASE_REVERSAL', 'SALE_REVERSAL'))
);

-- 10. WASTAGE
CREATE TABLE WASTAGE (
    WASTAGE_ID      NUMBER          PRIMARY KEY,
    PRODUCT_ID      NUMBER          NOT NULL,
    WASTAGE_DATE    DATE            DEFAULT TRUNC(SYSDATE) NOT NULL,
    QUANTITY        NUMBER(12,3)    NOT NULL,
    UNIT_COST       NUMBER(10,2)    NOT NULL,
    TOTAL_COST      NUMBER(12,2)    NOT NULL,
    REASON          VARCHAR2(100)   NOT NULL,
    NOTES           VARCHAR2(500),
    CREATED_BY      NUMBER,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_WASTE_PROD FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID),
    CONSTRAINT FK_WASTE_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_WASTE_QTY CHECK (QUANTITY > 0),
    CONSTRAINT CHK_WASTE_COST CHECK (UNIT_COST >= 0),
    CONSTRAINT CHK_WASTE_TOTAL CHECK (TOTAL_COST >= 0),
    CONSTRAINT CHK_WASTE_REASON CHECK (REASON IN ('Spoilage', 'Damage', 'Unsold Perishable', 'Quality Rejection', 'Expired', 'Other'))
);

-- 11. OPERATING_EXPENSES
CREATE TABLE OPERATING_EXPENSES (
    EXPENSE_ID      NUMBER          PRIMARY KEY,
    EXPENSE_DATE    DATE            DEFAULT TRUNC(SYSDATE) NOT NULL,
    CATEGORY        VARCHAR2(50)    NOT NULL,
    AMOUNT          NUMBER(10,2)    NOT NULL,
    DESCRIPTION     VARCHAR2(255)   NOT NULL,
    CREATED_BY      NUMBER,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_EXP_USER FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID),
    CONSTRAINT CHK_EXP_AMT CHECK (AMOUNT > 0),
    CONSTRAINT CHK_EXP_CAT CHECK (CATEGORY IN ('Rent', 'Electricity', 'Transport', 'Packaging', 'Salaries', 'Maintenance', 'Waste Disposal', 'Other'))
);

-- 12. AUDIT_LOGS
CREATE TABLE AUDIT_LOGS (
    AUDIT_ID            NUMBER          PRIMARY KEY,
    USER_ID             NUMBER,
    ACTION              VARCHAR2(50)    NOT NULL,
    TABLE_NAME          VARCHAR2(50)    NOT NULL,
    RECORD_ID           VARCHAR2(50),
    ACTION_TIMESTAMP    DATE            DEFAULT SYSDATE NOT NULL,
    DETAILS             VARCHAR2(1000),
    CONSTRAINT FK_AUDIT_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
);
