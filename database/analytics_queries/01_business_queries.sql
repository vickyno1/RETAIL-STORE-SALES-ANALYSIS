-- 1. Total Revenue by Day
SELECT 
    SALE_DATE,
    COUNT(DISTINCT SALE_ID) AS TOTAL_BATCHES,
    SUM(TOTAL_REVENUE) AS DAILY_REVENUE,
    SUM(TOTAL_COGS) AS DAILY_COGS,
    SUM(TOTAL_PROFIT) AS DAILY_GROSS_PROFIT,
    CASE WHEN SUM(TOTAL_REVENUE) > 0 
         THEN ROUND((SUM(TOTAL_PROFIT) / SUM(TOTAL_REVENUE)) * 100, 2) 
         ELSE 0 END AS GROSS_MARGIN_PCT
FROM SALES
WHERE STATUS = 'FINALIZED'
GROUP BY SALE_DATE
ORDER BY SALE_DATE DESC;

-- 2. Revenue by Month
SELECT 
    TO_CHAR(SALE_DATE, 'YYYY-MM') AS MONTH_KEY,
    TO_CHAR(SALE_DATE, 'Mon YYYY') AS MONTH_LABEL,
    COUNT(DISTINCT SALE_ID) AS TOTAL_DAYS_RECORDED,
    SUM(TOTAL_REVENUE) AS MONTHLY_REVENUE,
    SUM(TOTAL_COGS) AS MONTHLY_COGS,
    SUM(TOTAL_PROFIT) AS MONTHLY_GROSS_PROFIT,
    CASE WHEN SUM(TOTAL_REVENUE) > 0 
         THEN ROUND((SUM(TOTAL_PROFIT) / SUM(TOTAL_REVENUE)) * 100, 2) 
         ELSE 0 END AS GROSS_MARGIN_PCT
FROM SALES
WHERE STATUS = 'FINALIZED'
GROUP BY TO_CHAR(SALE_DATE, 'YYYY-MM'), TO_CHAR(SALE_DATE, 'Mon YYYY')
ORDER BY MONTH_KEY DESC;

-- 3. Quantity Sold by Product
SELECT 
    p.PRODUCT_CODE,
    p.PRODUCT_NAME,
    c.CATEGORY_NAME,
    p.UNIT,
    NVL(SUM(si.QUANTITY), 0) AS TOTAL_QUANTITY_SOLD,
    NVL(SUM(si.LINE_TOTAL), 0) AS TOTAL_REVENUE
FROM PRODUCTS p
JOIN CATEGORIES c ON p.CATEGORY_ID = c.CATEGORY_ID
LEFT JOIN SALES_ITEMS si ON p.PRODUCT_ID = si.PRODUCT_ID
LEFT JOIN SALES s ON si.SALE_ID = s.SALE_ID AND s.STATUS = 'FINALIZED'
GROUP BY p.PRODUCT_CODE, p.PRODUCT_NAME, c.CATEGORY_NAME, p.UNIT
ORDER BY TOTAL_QUANTITY_SOLD DESC;

-- 4. Best-Selling Vegetables (Ranked by Quantity)
SELECT * FROM (
    SELECT 
        p.PRODUCT_CODE,
        p.PRODUCT_NAME,
        p.UNIT,
        SUM(si.QUANTITY) AS TOTAL_KG_SOLD,
        SUM(si.LINE_TOTAL) AS TOTAL_REVENUE,
        SUM(si.LINE_TOTAL - si.COST_OF_GOODS_SOLD) AS GROSS_PROFIT
    FROM PRODUCTS p
    JOIN CATEGORIES c ON p.CATEGORY_ID = c.CATEGORY_ID
    JOIN SALES_ITEMS si ON p.PRODUCT_ID = si.PRODUCT_ID
    JOIN SALES s ON si.SALE_ID = s.SALE_ID
    WHERE c.CATEGORY_NAME = 'Vegetables'
      AND s.STATUS = 'FINALIZED'
    GROUP BY p.PRODUCT_CODE, p.PRODUCT_NAME, p.UNIT
    ORDER BY TOTAL_KG_SOLD DESC
) WHERE ROWNUM <= 10;

-- 5. Best-Selling Fruits (Ranked by Revenue)
SELECT * FROM (
    SELECT 
        p.PRODUCT_CODE,
        p.PRODUCT_NAME,
        p.UNIT,
        SUM(si.QUANTITY) AS TOTAL_QTY_SOLD,
        SUM(si.LINE_TOTAL) AS TOTAL_REVENUE,
        SUM(si.LINE_TOTAL - si.COST_OF_GOODS_SOLD) AS GROSS_PROFIT
    FROM PRODUCTS p
    JOIN CATEGORIES c ON p.CATEGORY_ID = c.CATEGORY_ID
    JOIN SALES_ITEMS si ON p.PRODUCT_ID = si.PRODUCT_ID
    JOIN SALES s ON si.SALE_ID = s.SALE_ID
    WHERE c.CATEGORY_NAME = 'Fruits'
      AND s.STATUS = 'FINALIZED'
    GROUP BY p.PRODUCT_CODE, p.PRODUCT_NAME, p.UNIT
    ORDER BY TOTAL_REVENUE DESC
) WHERE ROWNUM <= 10;

-- 6. Top 10 Products by Gross Profit
SELECT * FROM (
    SELECT 
        p.PRODUCT_CODE,
        p.PRODUCT_NAME,
        c.CATEGORY_NAME,
        SUM(si.LINE_TOTAL) AS TOTAL_REVENUE,
        SUM(si.COST_OF_GOODS_SOLD) AS TOTAL_COGS,
        SUM(si.LINE_TOTAL - si.COST_OF_GOODS_SOLD) AS GROSS_PROFIT,
        ROUND((SUM(si.LINE_TOTAL - si.COST_OF_GOODS_SOLD) / SUM(si.LINE_TOTAL)) * 100, 2) AS MARGIN_PCT
    FROM PRODUCTS p
    JOIN CATEGORIES c ON p.CATEGORY_ID = c.CATEGORY_ID
    JOIN SALES_ITEMS si ON p.PRODUCT_ID = si.PRODUCT_ID
    JOIN SALES s ON si.SALE_ID = s.SALE_ID
    WHERE s.STATUS = 'FINALIZED'
    GROUP BY p.PRODUCT_CODE, p.PRODUCT_NAME, c.CATEGORY_NAME
    ORDER BY GROSS_PROFIT DESC
) WHERE ROWNUM <= 10;

-- 7. Category-Wise Sales and Gross Profit Contribution
SELECT 
    c.CATEGORY_NAME,
    COUNT(DISTINCT p.PRODUCT_ID) AS PRODUCT_COUNT,
    SUM(si.QUANTITY) AS UNITS_SOLD,
    SUM(si.LINE_TOTAL) AS CATEGORY_REVENUE,
    SUM(si.COST_OF_GOODS_SOLD) AS CATEGORY_COGS,
    SUM(si.LINE_TOTAL - si.COST_OF_GOODS_SOLD) AS CATEGORY_GROSS_PROFIT,
    ROUND((SUM(si.LINE_TOTAL - si.COST_OF_GOODS_SOLD) / SUM(si.LINE_TOTAL)) * 100, 2) AS GROSS_MARGIN_PCT,
    ROUND((SUM(si.LINE_TOTAL) / (SELECT SUM(LINE_TOTAL) FROM SALES_ITEMS si2 JOIN SALES s2 ON si2.SALE_ID = s2.SALE_ID WHERE s2.STATUS = 'FINALIZED')) * 100, 2) AS REVENUE_SHARE_PCT
FROM CATEGORIES c
JOIN PRODUCTS p ON c.CATEGORY_ID = p.CATEGORY_ID
JOIN SALES_ITEMS si ON p.PRODUCT_ID = si.PRODUCT_ID
JOIN SALES s ON si.SALE_ID = s.SALE_ID
WHERE s.STATUS = 'FINALIZED'
GROUP BY c.CATEGORY_NAME
ORDER BY CATEGORY_REVENUE DESC;

-- 8. Products with Zero Sales
SELECT 
    p.PRODUCT_CODE,
    p.PRODUCT_NAME,
    c.CATEGORY_NAME,
    p.CURRENT_STOCK,
    p.SELLING_PRICE,
    p.CREATED_AT
FROM PRODUCTS p
JOIN CATEGORIES c ON p.CATEGORY_ID = c.CATEGORY_ID
WHERE p.STATUS = 'ACTIVE'
  AND p.PRODUCT_ID NOT IN (
      SELECT DISTINCT si.PRODUCT_ID 
      FROM SALES_ITEMS si 
      JOIN SALES s ON si.SALE_ID = s.SALE_ID 
      WHERE s.STATUS = 'FINALIZED'
  );

-- 9. Low Stock & Reorder Alert List
SELECT 
    p.PRODUCT_CODE,
    p.PRODUCT_NAME,
    c.CATEGORY_NAME,
    p.UNIT,
    p.CURRENT_STOCK,
    p.REORDER_LEVEL,
    (p.REORDER_LEVEL * 2 - p.CURRENT_STOCK) AS SUGGESTED_PURCHASE_QTY,
    s.SUPPLIER_NAME,
    s.PHONE AS SUPPLIER_PHONE
FROM PRODUCTS p
JOIN CATEGORIES c ON p.CATEGORY_ID = c.CATEGORY_ID
LEFT JOIN SUPPLIERS s ON p.PREFERRED_SUPPLIER_ID = s.SUPPLIER_ID
WHERE p.STATUS = 'ACTIVE'
  AND p.CURRENT_STOCK <= p.REORDER_LEVEL
ORDER BY (p.REORDER_LEVEL - p.CURRENT_STOCK) DESC;

-- 10. Supplier-Wise Purchase Expenditure
SELECT 
    s.SUPPLIER_CODE,
    s.SUPPLIER_NAME,
    s.CITY,
    COUNT(DISTINCT p.PURCHASE_ID) AS TOTAL_ORDERS,
    SUM(p.TOTAL_AMOUNT) AS TOTAL_EXPENDITURE
FROM SUPPLIERS s
JOIN PURCHASES p ON s.SUPPLIER_ID = p.SUPPLIER_ID
WHERE p.STATUS = 'COMPLETED'
GROUP BY s.SUPPLIER_CODE, s.SUPPLIER_NAME, s.CITY
ORDER BY TOTAL_EXPENDITURE DESC;

-- 11. Wastage and Spoilage by Product
SELECT 
    p.PRODUCT_CODE,
    p.PRODUCT_NAME,
    c.CATEGORY_NAME,
    p.UNIT,
    SUM(w.QUANTITY) AS TOTAL_WASTED_QTY,
    SUM(w.TOTAL_COST) AS TOTAL_WASTAGE_LOSS,
    COUNT(w.WASTAGE_ID) AS INCIDENT_COUNT
FROM PRODUCTS p
JOIN CATEGORIES c ON p.CATEGORY_ID = c.CATEGORY_ID
JOIN WASTAGE w ON p.PRODUCT_ID = w.PRODUCT_ID
GROUP BY p.PRODUCT_CODE, p.PRODUCT_NAME, c.CATEGORY_NAME, p.UNIT
ORDER BY TOTAL_WASTAGE_LOSS DESC;

-- 12. Current Inventory Valuation by Category
SELECT 
    c.CATEGORY_NAME,
    COUNT(p.PRODUCT_ID) AS PRODUCT_COUNT,
    SUM(p.CURRENT_STOCK) AS TOTAL_UNITS_IN_STOCK,
    ROUND(SUM(p.CURRENT_STOCK * p.CURRENT_AVERAGE_COST), 2) AS TOTAL_STOCK_VALUE
FROM CATEGORIES c
JOIN PRODUCTS p ON c.CATEGORY_ID = p.CATEGORY_ID
WHERE p.STATUS = 'ACTIVE'
GROUP BY c.CATEGORY_NAME
ORDER BY TOTAL_STOCK_VALUE DESC;
