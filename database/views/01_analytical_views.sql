-- 1. Daily Sales & Profit Summary
CREATE OR REPLACE VIEW VW_DAILY_SALES_SUMMARY AS
SELECT 
    s.SALE_DATE,
    COUNT(DISTINCT s.SALE_ID) AS BATCH_COUNT,
    COUNT(si.SALES_ITEM_ID) AS LINE_ITEMS_COUNT,
    NVL(SUM(si.QUANTITY), 0) AS TOTAL_QUANTITY_SOLD,
    NVL(SUM(si.LINE_TOTAL), 0) AS TOTAL_REVENUE,
    NVL(SUM(si.COST_OF_GOODS_SOLD), 0) AS TOTAL_COGS,
    NVL(SUM(si.LINE_TOTAL - si.COST_OF_GOODS_SOLD), 0) AS GROSS_PROFIT,
    CASE 
        WHEN NVL(SUM(si.LINE_TOTAL), 0) > 0 
        THEN ROUND((SUM(si.LINE_TOTAL - si.COST_OF_GOODS_SOLD) / SUM(si.LINE_TOTAL)) * 100, 2)
        ELSE 0 
    END AS GROSS_PROFIT_MARGIN_PCT
FROM SALES s
LEFT JOIN SALES_ITEMS si ON s.SALE_ID = si.SALE_ID
WHERE s.STATUS = 'FINALIZED'
GROUP BY s.SALE_DATE;

-- 2. Product Performance View
CREATE OR REPLACE VIEW VW_PRODUCT_PERFORMANCE AS
SELECT 
    p.PRODUCT_ID,
    p.PRODUCT_CODE,
    p.PRODUCT_NAME,
    c.CATEGORY_NAME,
    p.UNIT,
    p.PURCHASE_COST,
    p.CURRENT_AVERAGE_COST,
    p.SELLING_PRICE,
    p.CURRENT_STOCK,
    p.REORDER_LEVEL,
    p.STATUS,
    NVL(s_agg.TOTAL_QTY_SOLD, 0) AS TOTAL_QTY_SOLD,
    NVL(s_agg.TOTAL_REVENUE, 0) AS TOTAL_REVENUE,
    NVL(s_agg.TOTAL_COGS, 0) AS TOTAL_COGS,
    NVL(s_agg.GROSS_PROFIT, 0) AS GROSS_PROFIT,
    CASE 
        WHEN NVL(s_agg.TOTAL_REVENUE, 0) > 0 
        THEN ROUND((s_agg.GROSS_PROFIT / s_agg.TOTAL_REVENUE) * 100, 2)
        ELSE 0 
    END AS PROFIT_MARGIN_PCT,
    NVL(w_agg.WASTAGE_QTY, 0) AS WASTAGE_QTY,
    NVL(w_agg.WASTAGE_COST, 0) AS WASTAGE_COST
FROM PRODUCTS p
JOIN CATEGORIES c ON p.CATEGORY_ID = c.CATEGORY_ID
LEFT JOIN (
    SELECT 
        si.PRODUCT_ID,
        SUM(si.QUANTITY) AS TOTAL_QTY_SOLD,
        SUM(si.LINE_TOTAL) AS TOTAL_REVENUE,
        SUM(si.COST_OF_GOODS_SOLD) AS TOTAL_COGS,
        SUM(si.LINE_TOTAL - si.COST_OF_GOODS_SOLD) AS GROSS_PROFIT
    FROM SALES_ITEMS si
    JOIN SALES s ON si.SALE_ID = s.SALE_ID
    WHERE s.STATUS = 'FINALIZED'
    GROUP BY si.PRODUCT_ID
) s_agg ON p.PRODUCT_ID = s_agg.PRODUCT_ID
LEFT JOIN (
    SELECT 
        w.PRODUCT_ID,
        SUM(w.QUANTITY) AS WASTAGE_QTY,
        SUM(w.TOTAL_COST) AS WASTAGE_COST
    FROM WASTAGE w
    GROUP BY w.PRODUCT_ID
) w_agg ON p.PRODUCT_ID = w_agg.PRODUCT_ID;

-- 3. Category Performance View
CREATE OR REPLACE VIEW VW_CATEGORY_PERFORMANCE AS
SELECT 
    c.CATEGORY_ID,
    c.CATEGORY_NAME,
    COUNT(DISTINCT p.PRODUCT_ID) AS PRODUCT_COUNT,
    NVL(SUM(p.CURRENT_STOCK), 0) AS TOTAL_CATEGORY_STOCK,
    NVL(SUM(p.CURRENT_STOCK * p.CURRENT_AVERAGE_COST), 0) AS CATEGORY_STOCK_VALUE,
    NVL(SUM(vp.TOTAL_QTY_SOLD), 0) AS TOTAL_QTY_SOLD,
    NVL(SUM(vp.TOTAL_REVENUE), 0) AS TOTAL_REVENUE,
    NVL(SUM(vp.TOTAL_COGS), 0) AS TOTAL_COGS,
    NVL(SUM(vp.GROSS_PROFIT), 0) AS GROSS_PROFIT,
    CASE 
        WHEN NVL(SUM(vp.TOTAL_REVENUE), 0) > 0 
        THEN ROUND((SUM(vp.GROSS_PROFIT) / SUM(vp.TOTAL_REVENUE)) * 100, 2)
        ELSE 0 
    END AS PROFIT_MARGIN_PCT,
    NVL(SUM(vp.WASTAGE_COST), 0) AS WASTAGE_COST
FROM CATEGORIES c
LEFT JOIN PRODUCTS p ON c.CATEGORY_ID = p.CATEGORY_ID
LEFT JOIN VW_PRODUCT_PERFORMANCE vp ON p.PRODUCT_ID = vp.PRODUCT_ID
GROUP BY c.CATEGORY_ID, c.CATEGORY_NAME;

-- 4. Low Stock Alerts View
CREATE OR REPLACE VIEW VW_LOW_STOCK_ALERTS AS
SELECT 
    p.PRODUCT_ID,
    p.PRODUCT_CODE,
    p.PRODUCT_NAME,
    c.CATEGORY_NAME,
    p.UNIT,
    p.CURRENT_STOCK,
    p.REORDER_LEVEL,
    CASE 
        WHEN p.CURRENT_STOCK < p.REORDER_LEVEL 
        THEN (p.REORDER_LEVEL * 2) - p.CURRENT_STOCK
        ELSE p.REORDER_LEVEL
    END AS SUGGESTED_REORDER_QTY,
    p.PURCHASE_COST,
    s.SUPPLIER_NAME AS PREFERRED_SUPPLIER,
    s.PHONE AS SUPPLIER_PHONE,
    s.CITY AS SUPPLIER_CITY
FROM PRODUCTS p
JOIN CATEGORIES c ON p.CATEGORY_ID = c.CATEGORY_ID
LEFT JOIN SUPPLIERS s ON p.PREFERRED_SUPPLIER_ID = s.SUPPLIER_ID
WHERE p.STATUS = 'ACTIVE' 
  AND p.CURRENT_STOCK <= p.REORDER_LEVEL;

-- 5. Inventory Valuation View
CREATE OR REPLACE VIEW VW_INVENTORY_VALUATION AS
SELECT 
    p.PRODUCT_ID,
    p.PRODUCT_CODE,
    p.PRODUCT_NAME,
    c.CATEGORY_NAME,
    p.UNIT,
    p.CURRENT_STOCK,
    p.CURRENT_AVERAGE_COST,
    ROUND(p.CURRENT_STOCK * p.CURRENT_AVERAGE_COST, 2) AS INVENTORY_VALUE,
    p.REORDER_LEVEL,
    CASE 
        WHEN p.CURRENT_STOCK <= p.REORDER_LEVEL THEN 'LOW_STOCK'
        WHEN p.CURRENT_STOCK > (p.REORDER_LEVEL * 3) THEN 'OVERSTOCKED'
        ELSE 'OPTIMAL'
    END AS STOCK_STATUS
FROM PRODUCTS p
JOIN CATEGORIES c ON p.CATEGORY_ID = c.CATEGORY_ID
WHERE p.STATUS = 'ACTIVE';

-- 6. Monthly Business Financial Summary
CREATE OR REPLACE VIEW VW_MONTHLY_FINANCIAL_SUMMARY AS
SELECT 
    TO_CHAR(d.MONTH_DATE, 'YYYY-MM') AS MONTH_KEY,
    TO_CHAR(d.MONTH_DATE, 'Mon YYYY') AS MONTH_LABEL,
    NVL(sales_sum.REVENUE, 0) AS REVENUE,
    NVL(sales_sum.COGS, 0) AS COGS,
    NVL(sales_sum.GROSS_PROFIT, 0) AS GROSS_PROFIT,
    NVL(waste_sum.WASTAGE_COST, 0) AS WASTAGE_COST,
    NVL(exp_sum.EXPENSES, 0) AS OPERATING_EXPENSES,
    ROUND(NVL(sales_sum.GROSS_PROFIT, 0) - NVL(waste_sum.WASTAGE_COST, 0) - NVL(exp_sum.EXPENSES, 0), 2) AS NET_OPERATING_PROFIT_ESTIMATE
FROM (
    SELECT DISTINCT TRUNC(SALE_DATE, 'MM') AS MONTH_DATE FROM SALES WHERE STATUS = 'FINALIZED'
    UNION
    SELECT DISTINCT TRUNC(PURCHASE_DATE, 'MM') AS MONTH_DATE FROM PURCHASES WHERE STATUS = 'COMPLETED'
    UNION
    SELECT DISTINCT TRUNC(EXPENSE_DATE, 'MM') AS MONTH_DATE FROM OPERATING_EXPENSES
) d
LEFT JOIN (
    SELECT 
        TRUNC(SALE_DATE, 'MM') AS M_DATE,
        SUM(TOTAL_REVENUE) AS REVENUE,
        SUM(TOTAL_COGS) AS COGS,
        SUM(TOTAL_PROFIT) AS GROSS_PROFIT
    FROM SALES
    WHERE STATUS = 'FINALIZED'
    GROUP BY TRUNC(SALE_DATE, 'MM')
) sales_sum ON d.MONTH_DATE = sales_sum.M_DATE
LEFT JOIN (
    SELECT 
        TRUNC(WASTAGE_DATE, 'MM') AS M_DATE,
        SUM(TOTAL_COST) AS WASTAGE_COST
    FROM WASTAGE
    GROUP BY TRUNC(WASTAGE_DATE, 'MM')
) waste_sum ON d.MONTH_DATE = waste_sum.M_DATE
LEFT JOIN (
    SELECT 
        TRUNC(EXPENSE_DATE, 'MM') AS M_DATE,
        SUM(AMOUNT) AS EXPENSES
    FROM OPERATING_EXPENSES
    GROUP BY TRUNC(EXPENSE_DATE, 'MM')
) exp_sum ON d.MONTH_DATE = exp_sum.M_DATE;
