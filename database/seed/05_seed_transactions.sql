-- 2. SEED DAILY SALES TRANSACTIONS (Spanning past 30 days)
-- Helper script inserting historical finalized sales and sales items
DECLARE
    v_sale_id NUMBER;
    v_item_id NUMBER := 1;
    v_date DATE;
    v_day_rev NUMBER;
    v_day_cogs NUMBER;
    v_day_profit NUMBER;
    
    PROCEDURE ADD_HISTORICAL_ITEM(
        p_sid NUMBER, p_pid NUMBER, p_qty NUMBER, p_price NUMBER, p_cost NUMBER
    ) IS
        v_lt NUMBER := ROUND(p_qty * p_price, 2);
        v_cogs NUMBER := ROUND(p_qty * p_cost, 2);
    BEGIN
        INSERT INTO SALES_ITEMS (
            SALES_ITEM_ID, SALE_ID, PRODUCT_ID, QUANTITY, SELLING_PRICE,
            UNIT_COST_AT_SALE, DISCOUNT_AMOUNT, LINE_TOTAL, COST_OF_GOODS_SOLD
        ) VALUES (
            SEQ_SALES_ITEMS_ID.NEXTVAL, p_sid, p_pid, p_qty, p_price,
            p_cost, 0, v_lt, v_cogs
        );
        v_day_rev := v_day_rev + v_lt;
        v_day_cogs := v_day_cogs + v_cogs;
    END;

BEGIN
    FOR day_idx IN REVERSE 0..29 LOOP
        v_date := TRUNC(SYSDATE) - day_idx;
        v_day_rev := 0;
        v_day_cogs := 0;
        
        SELECT SEQ_SALES_ID.NEXTVAL INTO v_sale_id FROM DUAL;
        
        INSERT INTO SALES (
            SALE_ID, SALE_REF, SALE_DATE, TOTAL_REVENUE, TOTAL_COGS,
            TOTAL_PROFIT, STATUS, NOTES, CREATED_BY
        ) VALUES (
            v_sale_id, 'SALE-' || TO_CHAR(v_date, 'YYYYMMDD') || '-01',
            v_date, 0, 0, 0, 'FINALIZED', 'Daily sales closing for ' || TO_CHAR(v_date, 'DD-Mon-YYYY'), 1
        );
        
        -- High volume vegetables
        ADD_HISTORICAL_ITEM(v_sale_id, 1, 12 + MOD(day_idx * 3, 10), 35.00, 24.00); -- Tomato
        ADD_HISTORICAL_ITEM(v_sale_id, 4, 15 + MOD(day_idx * 2, 8), 40.00, 28.00);  -- Big Onion
        ADD_HISTORICAL_ITEM(v_sale_id, 5, 10 + MOD(day_idx, 6), 35.00, 25.00);      -- Potato
        ADD_HISTORICAL_ITEM(v_sale_id, 9, 8 + MOD(day_idx * 2, 7), 15.00, 8.00);    -- Coriander
        ADD_HISTORICAL_ITEM(v_sale_id, 10, 6 + MOD(day_idx, 5), 20.00, 10.00);     -- Palak
        
        -- High volume fruits
        ADD_HISTORICAL_ITEM(v_sale_id, 16, 8 + MOD(day_idx * 4, 7), 50.00, 35.00); -- Banana
        ADD_HISTORICAL_ITEM(v_sale_id, 18, 4 + MOD(day_idx, 4), 150.00, 110.00);   -- Apple
        ADD_HISTORICAL_ITEM(v_sale_id, 19, 5 + MOD(day_idx, 5), 80.00, 55.00);     -- Orange
        
        -- Staples groceries
        ADD_HISTORICAL_ITEM(v_sale_id, 26, 10 + MOD(day_idx * 5, 8), 56.00, 48.00);-- Ponni Rice
        ADD_HISTORICAL_ITEM(v_sale_id, 28, 4 + MOD(day_idx, 4), 165.00, 135.00);   -- Toor Dal
        ADD_HISTORICAL_ITEM(v_sale_id, 31, 6 + MOD(day_idx, 5), 45.00, 38.00);     -- Sugar
        ADD_HISTORICAL_ITEM(v_sale_id, 33, 3 + MOD(day_idx, 3), 130.00, 110.00);   -- Sunflower Oil
        
        v_day_profit := v_day_rev - v_day_cogs;
        
        UPDATE SALES
        SET TOTAL_REVENUE = v_day_rev,
            TOTAL_COGS = v_day_cogs,
            TOTAL_PROFIT = v_day_profit
        WHERE SALE_ID = v_sale_id;
    END LOOP;
END;
